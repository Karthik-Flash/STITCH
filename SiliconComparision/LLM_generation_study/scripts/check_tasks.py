#!/usr/bin/env python3
"""Validate tasks/ (built by scripts/make_tasks.py) with the STITCH runner's own functions (phase3/runner/p3_eval.py),
in the mode the generation pipeline uses for parents: simulation with the golden children (lib/), lint and synthesis
with port-only stubs of the children (only the module's own code counts). Writes reports/TASKS_CHECK.md.

  1. specs/ port blocks equal the golden ports (scripts/spec_ports.py --check)
  2. golden.v passes tb.v and every sign-off testbench; wall time of each run (the runner's simulation timeout
     is 60 s by default)
  3. golden.v is struct_clean in task mode (Yosys 0 latches, 0 loops; no hard Verilator warning)
  4. every mutant of that module (scripts/mutants.py) fails tb.v and fails every sign-off testbench

Run in WSL (Icarus, Verilator, Yosys on PATH):  python3 scripts/check_tasks.py
"""
import glob
import json
import os
import shutil
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mutants as MU  # noqa: E402
import spec_ports as SP  # noqa: E402

E = MU.E
STUDY = SP.STUDY
TASKS = os.path.join(STUDY, "tasks")


def sim(dut_text, task, tb, timeout=1200):
    wd = tempfile.mkdtemp(prefix="task_sim_")
    try:
        open(os.path.join(wd, "dut.v"), "w").write(dut_text)
        lib = sorted(glob.glob(os.path.join(TASKS, task, "lib", "*.v")))
        t0 = time.time()
        r = E.simulate(["dut.v"] + lib, os.path.join(TASKS, task, tb), wd, timeout=timeout)
        line = next((l for l in r["log"].splitlines() if E.PASS_TOKEN in l or E.FAIL_TOKEN in l), "")
        return r["outcome"], round(time.time() - t0, 1), line.strip()
    finally:
        shutil.rmtree(wd, ignore_errors=True)


def clean(task):
    wd = tempfile.mkdtemp(prefix="task_cln_")
    try:
        shutil.copy(os.path.join(TASKS, task, "golden.v"), os.path.join(wd, "dut.v"))
        stubs = sorted(glob.glob(os.path.join(TASKS, task, "stubs", "*.v")))
        v = E.lint(["dut.v"] + stubs, task, wd)
        y = E.synth(["dut.v"], task, wd, lib_files=tuple(stubs))
        ok = bool(y["ok"] and y["latch_events"] == 0 and y["loops"] == 0 and v["n_hard"] == 0)
        return ok, f"Yosys ok {y['ok']}, latches {y['latch_events']}, loops {y['loops']}, hard lint {v['n_hard']}"
    finally:
        shutil.rmtree(wd, ignore_errors=True)


def main():
    bad = []
    ports_ok = SP.main(check=True) == 0
    if not ports_ok:
        bad.append("spec ports")
    gold_rows, mut_rows = [], []
    for m in SP.MODULES:
        meta = json.load(open(os.path.join(TASKS, m, "meta.json")))
        golden = open(os.path.join(TASKS, m, "golden.v")).read()
        for tb in ["tb.v"] + meta["signoff_tbs"]:
            oc, secs, line = sim(golden, m, tb)
            gold_rows.append(f"| {m} | `{tb}` | {oc} | {secs} | {line} |")
            print(gold_rows[-1])
            if oc != "PASS":
                bad.append(f"golden {m} {tb}")
        ok, detail = clean(m)
        gold_rows.append(f"| {m} | struct_clean (task mode) | {'yes' if ok else 'NO'} | | {detail} |")
        print(gold_rows[-1])
        if not ok:
            bad.append(f"golden {m} not clean")
        for i, (mm, old, new, bug) in enumerate(MU.MUTANTS, 1):
            if mm != m:
                continue
            assert golden.count(old) == 1, (m, old)
            res = {tb: sim(golden.replace(old, new), m, tb)[0] for tb in ["tb.v"] + meta["signoff_tbs"]}
            killed = all(v != "PASS" for v in res.values())
            mut_rows.append(f"| M{i} | {m} | {bug} | " + ", ".join(f"`{k}` {v}" for k, v in res.items()) +
                            f" | {'caught by all' if killed else 'MISSED'} |")
            print(mut_rows[-1])
            if not killed:
                bad.append(f"M{i} not caught by every testbench")
    md = ["# Task check", "",
          "Generated by `scripts/check_tasks.py` from `tasks/` (built by `scripts/make_tasks.py`). Simulation uses the",
          "golden children in `lib/`; lint and synthesis use port-only stubs of the children, as the generation pipeline",
          "does, so only the module's own code is judged. Seconds are wall time on the machine that ran this report.", "",
          f"**Result: {'all checks pass' if not bad else 'FAILED: ' + '; '.join(bad)}.**", "",
          f"Spec port blocks equal the golden ports: {'yes' if ports_ok else 'NO'}.", "",
          "## Golden", "", "| task | testbench / check | result | seconds | summary line / detail |",
          "|---|---|---|---|---|", *gold_rows, "",
          "## Mutants (scripts/mutants.py): each must fail the loop testbench and every sign-off testbench", "",
          "| id | task | bug | results | verdict |", "|---|---|---|---|---|", *mut_rows, ""]
    open(os.path.join(STUDY, "reports", "TASKS_CHECK.md"), "w", newline="\n").write("\n".join(md))
    print("OK" if not bad else "FAILED: " + "; ".join(bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
