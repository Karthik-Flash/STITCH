"""Mutation test of the golden testbenches: put one known bug at a time into a copy of the golden RTL and run
the testbench of the mutated module and the router testbench. Every mutant must be caught by at least one.
Writes reports/MUTANTS.md.

Run in WSL:  python3 scripts/mutants.py
"""
import os
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_golden as G  # noqa: E402

E = G.E
# (module, original text, mutated text, bug)
MUTANTS = [
    ("fifo", "assign almost_full = (count >= 3'd3);", "assign almost_full = (count >= 3'd4);",
     "full flag one slot late"),
    ("fifo", "wire do_wr = wr_en && (count != 3'd4);", "wire do_wr = wr_en;", "write accepted when full"),
    ("fifo", "else if (do_rd && !do_wr)", "else if (do_rd)", "count wrong on simultaneous read and write"),
    ("route_compute", "(dest_row > curr_row) ? 5'b00001", "(dest_row >= curr_row) ? 5'b00001", "row compare off by one"),
    ("route_compute", "(dest_col > curr_col) ? 5'b00100", "(dest_col > curr_col) ? 5'b01000", "link3 and link4 swapped"),
    ("route_compute", "wire       is_head = (flit[30:29] == 2'b01);", "wire       is_head = (flit[30:29] != 2'b11);",
     "body and tail flits routed as heads"),
    ("rr_arbiter", "else if (advance && (gnt != 4'b0000))", "else if (1'b0)", "priority never moves (fixed priority)"),
    ("rr_arbiter", "last <= 2'd3;", "last <= 2'd0;", "wrong priority after reset"),
    ("flit_mux", "                                    32'h6000_0000;", "                                    32'h0000_0000;",
     "idle output is a body flit"),
    ("flit_mux", "(sel == 4'b0100) ? in2 :", "(sel == 4'b0100) ? in3 :", "inputs 2 and 3 crossed"),
    ("input_port", "else if (rd_en && !empty && is_head)", "else if (rd_en && !empty)",
     "held route overwritten by body flits"),
    ("input_port", ".wr_en(data_in[30:29] != 2'b11),", ".wr_en(1'b1),", "idle flits stored"),
    ("output_port", "owner    <= (sel_flit[30:29] == 2'b10) ? 4'b0000 : sel;", "owner    <= 4'b0000;",
     "no wormhole hold (packets can interleave)"),
    ("output_port", "(req != 4'b0000)) && !full_in;", "(req != 4'b0000));", "full_in ignored"),
    ("output_port", "(locked ? ((owner & req) != 4'b0000) : (req != 4'b0000))",
     "(locked ? (req != 4'b0000) : (req != 4'b0000))", "held output sends for any requester"),
    ("output_port", "assign pop = send ? sel : 4'b0000;", "assign pop = sel & req;", "flit popped while blocked"),
    ("output_port", "(sel_flit[30:29] == 2'b10) ? 4'b0000", "(sel_flit[30:29] == 2'b01) ? 4'b0000",
     "head flit releases the hold instead of the tail"),
    ("router_5port", "| pop_l4[2] | pop_c[2];", "| pop_l4[2] | pop_c[3];", "core pop wired to the wrong input"),
    ("router_5port", ".req({req_c[3], req_l3[3], req_l2[3], req_l1[3]}),",
     ".req({req_c[3], req_l3[3], req_l1[3], req_l2[3]}),", "link4 output requesters swapped"),
]


def run(module, old, new):
    rtl = tempfile.mkdtemp(prefix="mut_rtl_")
    try:
        for f in os.listdir(G.RTL):
            shutil.copy(os.path.join(G.RTL, f), rtl)
        p = os.path.join(rtl, module + ".v")
        s = open(p).read()
        assert s.count(old) == 1, (module, old)
        open(p, "w").write(s.replace(old, new))
        out = {}
        for tb in dict.fromkeys([module, "router_5port"]):
            wd = tempfile.mkdtemp(prefix="mut_sim_")
            try:
                out[tb] = E.simulate(G.files(tb, rtl), os.path.join(G.TB, f"tb_{tb}.v"), wd, timeout=300)["outcome"]
            finally:
                shutil.rmtree(wd, ignore_errors=True)
        return out
    finally:
        shutil.rmtree(rtl, ignore_errors=True)


def main():
    rows, caught = [], 0
    for i, (m, old, new, bug) in enumerate(MUTANTS, 1):
        r = run(m, old, new)
        own, top = r[m], r["router_5port"]
        killed = own != "PASS" or top != "PASS"
        caught += killed
        rows.append(f"| M{i} | {m} | {bug} | {own} | {top if m != 'router_5port' else '(same)'} | "
                    f"{'caught' if killed else 'MISSED'} |")
        print(rows[-1])
    md = ["# Mutation test of the golden testbenches", "",
          "Generated by `scripts/mutants.py`. Each mutant puts one bug into a copy of the golden RTL, then runs the",
          "testbench of the mutated module and the router testbench (`tb_router_5port.v`). PASS means the bug went",
          "unnoticed by that testbench. The router testbench checks delivery, order, packet integrity and flow",
          "control, not the arbitration order, so bugs that only change which waiting packet goes first are caught",
          "by the module testbench alone.", "",
          f"**Result: {caught} of {len(MUTANTS)} mutants caught.**", "",
          "| id | module | bug | module tb | router tb | verdict |", "|---|---|---|---|---|---|", *rows, ""]
    open(os.path.join(G.STUDY, "reports", "MUTANTS.md"), "w", newline="\n").write("\n".join(md))
    print(f"{caught} of {len(MUTANTS)} caught")
    return 0 if caught == len(MUTANTS) else 1


if __name__ == "__main__":
    sys.exit(main())
