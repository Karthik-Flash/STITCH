"""Describe the original ZedBoard project in original_2x2_mesh_zedboard/ (read-only): provenance, module list,
differences from the repo copy phase3/designs/mesh2x2_ref, and the numbers in its own Vivado 2014.4 reports.
Writes reports/ORIGINAL.md.

Run anywhere with Python 3:  python scripts/describe_original.py
"""
import os
import re

STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(os.path.dirname(STUDY))
ORIG = os.path.join(STUDY, "original_2x2_mesh_zedboard")
PROJ = os.path.join(ORIG, "project_4on2014edition")
SRCS = os.path.join(PROJ, "project_4on2014edition.srcs")
SRC = os.path.join(SRCS, "sources_1", "imports", "untitled folder")
RUNS = os.path.join(PROJ, "project_4on2014edition.runs")
REPO_COPY = os.path.join(REPO, "phase3", "designs", "mesh2x2_ref")


def read(p):
    return open(p, encoding="latin-1").read().replace("\r", "")


def tokens(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return re.findall(r"[A-Za-z_][A-Za-z0-9_$]*|\d+'[sS]?[bBoOdDhH][0-9a-fA-FxXzZ_?]+|\d+|\S", text)


def modules(folder):
    out = {}
    for f in sorted(os.listdir(folder)):
        if f.endswith(".v"):
            t = tokens(read(os.path.join(folder, f)))
            i = 0
            while "module" in t[i:]:
                i = t.index("module", i)
                j = t.index("endmodule", i)
                out[t[i + 1]] = (f, t[i:j + 1])
                i = j + 1
    return out


def num(pat, text, cast=int):
    m = re.search(pat, text, re.M)
    return cast(m.group(1)) if m else None


def drc_rules(text):
    out = {}
    for r in re.findall(r"^([A-Z0-9]+-\d+)#\d+ ", text, re.M):
        out[r] = out.get(r, 0) + 1
    return out


def impl_numbers(run, prefix):
    d = os.path.join(RUNS, run)
    util = read(os.path.join(d, f"{prefix}_utilization_placed.rpt"))
    tim = read(os.path.join(d, f"{prefix}_timing_summary_routed.rpt"))
    drc = read(os.path.join(d, f"{prefix}_drc_routed.rpt"))
    pwr = read(os.path.join(d, f"{prefix}_power_routed.rpt"))
    u = lambda n: num(r"^\|\s+" + re.escape(n) + r"\s+\|\s+(\d+)\s+\|", util)
    roots = re.findall(r"There (?:is|are) (\d+) register/latch pins? with no clock driven by root clock pin: (\S+)", tim)
    return {
        "device": num(r"^\| Device\s+:\s+(\S+)", util, str) or num(r"^\| Device\s+:\s+(\S+)", tim, str),
        "date": num(r"^\| Date\s+:\s+(.+?)\s*$", tim, str),
        "tool": num(r"^\| Tool Version\s+:\s+(.+?)\s*$", tim, str),
        "luts": u("Slice LUTs"), "lut_mem": u("LUT as Memory"), "regs": u("Slice Registers"),
        "latch": u("Register as Latch"), "bram": num(r"^\|\s+Block RAM Tile\s+\|\s+([\d.]+)\s+\|", util, float),
        "iob": u("Bonded IOB"), "clock_roots": len(roots),
        "no_clock_clk": next((int(n) for n, pin in roots if pin == "clk"), 0),
        "unconstrained": num(r"There are (\d+) pins that are not constrained for maximum delay\.", tim),
        "loops": num(r"There are (\d+) combinational loops in the design", tim),
        "clocks": "none" if re.search(r"No user specified timing constraints|There are 0 clocks", tim) or
                  not re.search(r"^Clock\s+Waveform", tim, re.M) else "defined",
        "drc": drc_rules(drc), "power": num(r"^\| Total On-Chip Power \(W\)\s+\|\s+([\d.]+)", pwr, float),
    }


def main():
    xpr = read(os.path.join(PROJ, "project_4on2014edition.xpr"))
    opt = lambda name: num(r'<Option Name="' + name + r'" Val="([^"]+)"', xpr, str)
    version = num(r"Product Version: Vivado v(\S+)", xpr, str)
    location = num(r'<Project [^>]*Path="([^"]+)"', xpr, str)
    xdc = read(os.path.join(SRCS, "constrs_1", "new", "router4.xdc"))
    orig, repo = modules(SRC), modules(REPO_COPY)
    rows = []
    for m in sorted(set(orig) | set(repo)):
        if m not in repo:
            rows.append(f"| {m} | {orig[m][0]} | only in the original |")
        elif m not in orig:
            rows.append(f"| {m} | {repo[m][0]} (repo) | only in the repo copy |")
        else:
            a, b = orig[m][1], repo[m][1]
            same = a == b or "".join(a) == "".join(b)   # the second test ignores spacing inside a literal
            rows.append(f"| {m} | {orig[m][0]} | {'same' if same else 'DIFFERENT'} |")
    n_diff = sum("DIFFERENT" in r for r in rows)
    synth_log = read(os.path.join(RUNS, "synth_3", "runme.log"))
    latch_msgs = len(re.findall(r"\[Synth 8-327\]", synth_log))
    b = impl_numbers("impl_3", "main")
    pngs = sorted(os.listdir(os.path.join(ORIG, "Outputs_2x2")))
    fmt = lambda d: ", ".join(f"{k} {v}" for k, v in sorted(d.items()))
    md = [
        "# The original ZedBoard 2x2 mesh (`original_2x2_mesh_zedboard/`)", "",
        "Generated by `scripts/describe_original.py` from the files as downloaded (nothing in the folder is changed).",
        "",
        "## What it is", "",
        f"- A Vivado {version} project, part {opt('Part')}, board {opt('BoardPart')} (ZedBoard).",
        f"- Original location recorded in the project file: `{location}`.",
        f"- Top `{opt('TopModule')}` (`Main.v`): the 2x2 mesh `top_4_router`"
        " (four 5-port routers `top_module`, 4 virtual channels per port) with a VIO core driving the core inputs",
        "  and an ILA core capturing them, for testing on the board.",
        "- `NOC_4_ROUTER.v`: the simulation testbench (head, body and tail flits from router 1's core).",
        f"- `Outputs_2x2/`: {len(pngs)} screenshots of the Vivado hardware manager with the bitstream on the board "
        "(`r1_r2`, `r1_r3`, `r1_r4` x head, payload, tail flit): VIO sets router 1's core input, the flit appears at",
        "  the destination core output.",
        f"- `project_4on2014edition.runs/impl_3/main.bit`: the bitstream ({b['date']}).", "",
        "## Same router as the repo copy", "",
        f"`phase3/designs/mesh2x2_ref` (used by the earlier studies) holds the same router tree. Module bodies compared",
        f"token by token with comments removed: {n_diff} of {len(rows)} modules differ.", "",
        "| module | file | versus the repo copy |", "|---|---|---|", *rows, "",
        "## Its own Vivado results (routed run `impl_3`, top `main` with VIO and ILA)", "",
        f"Constraints (`router4.xdc`): clock pin only, no `create_clock`; "
        f"{'combinational loops allowed (ALLOW_COMBINATORIAL_LOOPS) and DRC LUTLP-1 lowered to a warning' if 'LUTLP-1' in xdc else ''}.", "",
        "| metric | value |", "|---|---|",
        f"| tool, device | {b['tool']}, {b['device']} |",
        f"| Slice LUTs (as memory) | {b['luts']} ({b['lut_mem']}) |",
        f"| Slice registers (as latches) | {b['regs']} ({b['latch']}) |",
        f"| Block RAM tiles (ILA buffer) | {b['bram']:g} |",
        f"| register/latch pins with no clock driven by `clk` | {b['no_clock_clk']} |",
        f"| clock roots without a clock definition (`clk` and internal nets used as clocks) | {b['clock_roots']} |",
        f"| pins not constrained for maximum delay | {b['unconstrained']} |",
        f"| combinational loops | {b['loops']} |",
        f"| synthesis latch messages [Synth 8-327] (synth_3) | {latch_msgs} |",
        f"| DRC violations by rule | {fmt(b['drc'])} |",
        f"| total on-chip power | {b['power']} W |", "",
        "No timing figure exists for the original: without a clock constraint Vivado times nothing. It was verified",
        "on the board by observing flits, not by timing analysis.", ""]
    open(os.path.join(STUDY, "reports", "ORIGINAL.md"), "w", newline="\n").write("\n".join(md))
    print(f"{len(rows)} modules, {n_diff} different; latches {b['latch']}, loops {b['loops']}, "
          f"unconstrained {b['unconstrained']}, DRC {fmt(b['drc'])}")


if __name__ == "__main__":
    main()
