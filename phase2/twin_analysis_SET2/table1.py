"""
phase2/twin_analysis/table1.py -- Table 1 (paper): full 42x5 module x
model-condition grid for the Twin run.

Rows: 42 modules, grouped by (functional_class, difficulty_tier) --
group order and within-group module order both come from
_data.sorted_modules_by_group(), so the LaTeX and CSV outputs agree with
every other deliverable in this directory on row order. A bold group
header row is inserted (LaTeX) / a blank separator + label row (CSV)
whenever the (functional_class, difficulty_tier) pair changes.

Columns: the 5 model-conditions in the locked order from _data.py
(RTLCoder native, RTLCoder shared, deepseek-coder shared, gemma3:4b
shared, llama3.1 shared).

Cell format: "p/3", light-green background if p==3, light-red if p==0,
no color otherwise (LaTeX only -- CSV is plain "p/3" strings, colorless
by nature).

Usage: python phase2/twin_analysis/table1.py
Output: table1_full_grid.tex (LaTeX booktabs, requires \\usepackage{colortbl}
        or xcolor[table] for \\cellcolor -- noted in the file's own header
        comment), table1_full_grid.csv
"""
import csv
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
import _data  # noqa: E402

OUT_TEX = os.path.join(_HERE, "table1_full_grid.tex")
OUT_CSV = os.path.join(_HERE, "table1_full_grid.csv")


def _cell_color(p):
    if p == 3:
        return "green!15"
    if p == 0:
        return "red!15"
    return None


def _tex_escape(s):
    return s.replace("_", r"\_")


def build():
    entries = _data.load_master_log()
    counts = _data.pivot_pass_counts(entries)
    categories = _data.load_categories()
    modules = _data.sorted_modules_by_group(categories)

    rows = []  # (module, group_label_or_None, [p0..p4])
    last_group = None
    for m in modules:
        info = categories[m]
        group = (info["functional_class"], info["difficulty_tier"])
        group_label = None
        if group != last_group:
            group_label = f"{info['functional_class']} -- {info['difficulty_tier']}"
            last_group = group
        cell_values = [
            counts.get((m, model, cond), 0)
            for model, cond, _label in _data.MODEL_CONDITIONS
        ]
        rows.append((m, group_label, cell_values))

    return rows


def write_tex(rows):
    header_labels = [label for _m, _c, label in _data.MODEL_CONDITIONS]
    lines = []
    lines.append("% Auto-generated by phase2/twin_analysis/table1.py -- do not hand-edit.")
    lines.append("% Requires \\usepackage{colortbl} or \\usepackage[table]{xcolor} in the")
    lines.append("% preamble for \\cellcolor to work.")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Twin run: pass count (of $N{=}3$) per module and model-condition, "
                 r"42 modules, 630 runs total, 0 errors, $T{=}0.5$, baseline-only.}")
    lines.append(r"\label{tab:twin-full-grid}")
    lines.append(r"\begin{tabular}{l" + "c" * len(header_labels) + "}")
    lines.append(r"\toprule")
    lines.append("Module & " + " & ".join(header_labels) + r" \\")
    lines.append(r"\midrule")
    for module, group_label, cell_values in rows:
        if group_label:
            lines.append(r"\multicolumn{" + str(len(header_labels) + 1) + "}{l}{\\textbf{"
                          + _tex_escape(group_label) + "}} \\\\")
        cells = []
        for p in cell_values:
            color = _cell_color(p)
            text = f"{p}/3"
            cells.append(f"\\cellcolor{{{color}}}{text}" if color else text)
        lines.append(_tex_escape(module) + " & " + " & ".join(cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    with open(OUT_TEX, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_csv(rows):
    header_labels = [label for _m, _c, label in _data.MODEL_CONDITIONS]
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["module", "functional_class_tier_group"] + header_labels)
        last_group = None
        for module, group_label, cell_values in rows:
            group_for_csv = group_label if group_label else last_group
            if group_label:
                last_group = group_label
            w.writerow([module, group_for_csv] + [f"{p}/3" for p in cell_values])


def main():
    rows = build()
    assert len(rows) == 42, f"expected 42 rows, got {len(rows)}"
    write_tex(rows)
    write_csv(rows)

    # Verification: total passes across the grid must match the
    # brief's stated cross-check.
    total_passes = sum(sum(vals) for _m, _g, vals in rows)
    print(f"Wrote {OUT_TEX} and {OUT_CSV} ({len(rows)} rows)")
    print(f"Sum of all cell pass-counts: {total_passes} "
          f"(cross-check against sum(1 for e in master_log if e['pass']))")


if __name__ == "__main__":
    main()
