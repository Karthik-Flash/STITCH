"""
phase2/twin_analysis/table2.py -- Table 2 (paper): the fine-tuning-twin
verdict, per recoverable-band module.

Delta is a raw PASS-COUNT difference (RTLCoder shared minus
deepseek-coder shared, each in {0,1,2,3} since N=3) -- not a percentage
-- matching the brief's own threshold units (+-2 out of a possible +-3
range only makes sense as a count difference).

Verdict (exhaustive over delta in {-3..3}):
  Twin wins:  delta >= +2   (+2, +3)
  Base wins:  delta <= -2   (-2, -3)
  Tied:       |delta| <= 1  (-1, 0, +1)

Usage: python phase2/twin_analysis/table2.py
Output: table2_twin_decision.tex, table2_twin_decision.csv
"""
import csv
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
import _data  # noqa: E402

OUT_TEX = os.path.join(_HERE, "table2_twin_decision.tex")
OUT_CSV = os.path.join(_HERE, "table2_twin_decision.csv")

RTLCODER_SHARED = ("rtlcoder-deepseek-v1.1", "shared")
DEEPSEEK_SHARED = ("deepseek-coder:6.7b", "shared")


def _verdict(delta):
    if delta >= 2:
        return "Twin wins"
    if delta <= -2:
        return "Base wins"
    return "Tied"


def build():
    entries = _data.load_master_log()
    counts = _data.pivot_pass_counts(entries)
    categories = _data.load_categories()
    recoverable = sorted(m for m, info in categories.items() if info["difficulty_tier"] == "recoverable")

    rows = []
    for m in recoverable:
        twin_p = counts.get((m,) + RTLCODER_SHARED, 0)
        base_p = counts.get((m,) + DEEPSEEK_SHARED, 0)
        delta = twin_p - base_p
        rows.append((m, twin_p, base_p, delta, _verdict(delta)))
    return rows


def write_csv(rows):
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["module", "rtlcoder_shared", "deepseek_coder_shared", "delta", "verdict"])
        for m, twin_p, base_p, delta, verdict in rows:
            w.writerow([m, f"{twin_p}/3", f"{base_p}/3", delta, verdict])


def write_tex(rows, summary_line):
    lines = []
    lines.append("% Auto-generated by phase2/twin_analysis/table2.py -- do not hand-edit.")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Fine-tuning twin comparison verdict, recoverable-band modules "
                 r"only ($N{=}3$ per cell). $\Delta$ = RTLCoder shared $-$ deepseek-coder shared, "
                 r"in pass count (range $-3$ to $+3$).}")
    lines.append(r"\label{tab:twin-decision}")
    lines.append(r"\begin{tabular}{lcccc}")
    lines.append(r"\toprule")
    lines.append(r"Module & RTLCoder shared & deepseek-coder shared & $\Delta$ & Verdict \\")
    lines.append(r"\midrule")
    for m, twin_p, base_p, delta, verdict in rows:
        m_tex = m.replace("_", r"\_")
        delta_str = f"{delta:+d}"
        lines.append(f"{m_tex} & {twin_p}/3 & {base_p}/3 & {delta_str} & {verdict} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\vspace{4pt}")
    lines.append(r"\par\small " + summary_line)
    lines.append(r"\end{table}")
    with open(OUT_TEX, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def main():
    rows = build()
    wins = sum(1 for r in rows if r[4] == "Twin wins")
    losses = sum(1 for r in rows if r[4] == "Base wins")
    ties = sum(1 for r in rows if r[4] == "Tied")
    total = len(rows)

    if wins > losses:
        signal = "a modest edge"
    elif losses > wins:
        signal = "a modest disadvantage"
    else:
        signal = "no net advantage"

    summary_line = (
        f"RTLCoder-Deepseek-v1.1 wins {wins}, ties {ties}, loses {losses} of "
        f"{total} recoverable-band modules on the fine-tuning twin comparison "
        f"-- {signal} on this comparison, not a decisive one."
    )

    write_csv(rows)
    write_tex(rows, summary_line)
    print(f"Wrote {OUT_TEX} and {OUT_CSV} ({total} rows)")
    print(summary_line)


if __name__ == "__main__":
    main()
