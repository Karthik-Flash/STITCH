"""
phase2/set1_analysis/cost_analysis.py -- Set 1's load-bearing deliverable:
the cost result. Extends Phase 1's Table 4 (STITCH_EXT.pdf p.4 /
phase1/PHASE1_TASK3_ANALYSIS.md Sec.3) to RTLLM scale (42 modules x 3
models x N=3, minus 6 known transient errors = 1506 valid runs).

Pass rate is pooled across all 42 modules (the regression check -- must
not lose ground). Tool-invocation cost is the win. See
_data.load_run_cost's docstring/comments for exactly how each condition's
verilator/yosys call counts are derived (real per-iteration counts for
sem_escalate/sem_escalate_restart; exact, verified-not-approximate
reconstruction for baseline/sem_adv).

Usage: python phase2/set1_analysis/cost_analysis.py
Output: cost_summary.tex, cost_summary.csv,
        fig1_cost_vs_passrate.png (300 DPI), fig1_cost_vs_passrate.pdf
"""
import csv
import os
import sys
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
import _data  # noqa: E402

OUT_TEX = os.path.join(_HERE, "cost_summary.tex")
OUT_CSV = os.path.join(_HERE, "cost_summary.csv")
OUT_FIG_PNG = os.path.join(_HERE, "fig1_cost_vs_passrate.png")
OUT_FIG_PDF = os.path.join(_HERE, "fig1_cost_vs_passrate.pdf")

CONDITION_LABEL = {
    "baseline": "baseline",
    "sem_adv": "sem\\_adv",
    "sem_escalate": "sem\\_escalate",
    "sem_escalate_restart": "sem\\_escalate\\_restart",
}
CONDITION_LABEL_PLAIN = {
    "baseline": "baseline",
    "sem_adv": "sem_adv",
    "sem_escalate": "sem_escalate",
    "sem_escalate_restart": "sem_escalate_restart",
}


def collect_costs(entries):
    """Returns {condition: {"tokens": [...], "verilator": [...],
    "yosys": [...], "tool_calls": [...], "iterations": [...]}} pooled
    across all 42 modules x 3 models x N=3, and separately the set of
    (module, model, condition, replicate) whose cost file was missing/
    malformed beyond the known 6 errors."""
    per_cond = {c: defaultdict(list) for c in _data.CONDITIONS}
    dropped_unexpected = []
    n_read = 0
    for module, model, condition, rep in _data.iter_valid_runs(entries):
        cost = _data.load_run_cost(module, model, condition, rep)
        if cost is None:
            dropped_unexpected.append((module, model, condition, rep))
            continue
        n_read += 1
        per_cond[condition]["tokens"].append(cost["tokens"])
        per_cond[condition]["verilator"].append(cost["verilator_calls"])
        per_cond[condition]["yosys"].append(cost["yosys_calls"])
        per_cond[condition]["tool_calls"].append(cost["tool_calls"])
        per_cond[condition]["iterations"].append(cost["iterations"])
    return per_cond, dropped_unexpected, n_read


def pooled_pass_rate(entries):
    """{condition: (n_pass, n_valid)} pooled across all 42 modules x 3
    models x N=3 (minus the 6 known-error replicates)."""
    counts = _data.pivot_pass_counts(entries)
    result = {c: [0, 0] for c in _data.CONDITIONS}
    for (module, model, condition), (n_pass, n_valid) in counts.items():
        result[condition][0] += n_pass
        result[condition][1] += n_valid
    return {c: tuple(v) for c, v in result.items()}


def _mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def build_summary(per_cond, pass_rates):
    rows = []
    for c in _data.CONDITIONS:
        d = per_cond[c]
        n_pass, n_valid = pass_rates[c]
        rows.append({
            "condition": c,
            "n_runs": len(d["tokens"]),
            "mean_tokens": _mean(d["tokens"]),
            "mean_tool_calls": _mean(d["tool_calls"]),
            "mean_verilator_calls": _mean(d["verilator"]),
            "mean_yosys_calls": _mean(d["yosys"]),
            "mean_iterations": _mean(d["iterations"]),
            "pass_rate": n_pass / n_valid if n_valid else float("nan"),
            "n_pass": n_pass,
            "n_valid": n_valid,
        })
    return rows


def write_tex(rows, reduction_pct):
    lines = []
    lines.append("% Auto-generated by phase2/set1_analysis/cost_analysis.py -- do not hand-edit.")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Set 1: mean cost per run by STITCH condition, "
                 r"42 RTLLM modules $\times$ 3 models $\times N{=}3$, 1506/1512 valid "
                 r"runs (6 transient timeouts dropped), $T{=}0.1$. "
                 r"Verilator+Yosys calls/run is the load-bearing axis: "
                 rf"sem\_escalate cuts it {reduction_pct:.1f}\% vs. sem\_adv "
                 r"(Phase 1's matched result: 35--45\%).}")
    lines.append(r"\label{tab:set1-cost}")
    lines.append(r"\begin{tabular}{lrrr}")
    lines.append(r"\toprule")
    lines.append(r"Condition & mean tokens/run & Verilator+Yosys calls/run & mean iterations/run \\")
    lines.append(r"\midrule")
    for r in rows:
        lines.append(
            f"{CONDITION_LABEL[r['condition']]} & {r['mean_tokens']:.0f} & "
            f"{r['mean_tool_calls']:.2f} & {r['mean_iterations']:.2f} \\\\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    with open(OUT_TEX, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_csv(rows):
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["condition", "n_runs", "mean_tokens_per_run",
                     "mean_verilator_calls_per_run", "mean_yosys_calls_per_run",
                     "mean_tool_calls_per_run", "mean_iterations_per_run",
                     "n_pass", "n_valid", "pass_rate"])
        for r in rows:
            w.writerow([
                r["condition"], r["n_runs"], f"{r['mean_tokens']:.2f}",
                f"{r['mean_verilator_calls']:.4f}", f"{r['mean_yosys_calls']:.4f}",
                f"{r['mean_tool_calls']:.4f}", f"{r['mean_iterations']:.4f}",
                r["n_pass"], r["n_valid"], f"{r['pass_rate']:.4f}",
            ])


def write_fig(rows):
    labels = [CONDITION_LABEL_PLAIN[r["condition"]] for r in rows]
    tool_calls = [r["mean_tool_calls"] for r in rows]
    pass_rates = [r["pass_rate"] for r in rows]
    x = np.arange(len(labels))

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

    ax1.bar(x, tool_calls, color="#C44E52", edgecolor="black", linewidth=0.5)
    ax1.set_xticks(x)
    ax1.set_xticklabels(labels, rotation=20, ha="right")
    ax1.set_ylabel("Mean Verilator+Yosys calls/run")
    ax1.set_title("(a) Tool-invocation cost per condition")
    ax1.grid(axis="y", linestyle=":", alpha=0.4)
    for i, v in enumerate(tool_calls):
        ax1.text(i, v + max(tool_calls) * 0.02, f"{v:.2f}", ha="center", fontsize=9)

    ax2.bar(x, pass_rates, color="#4C72B0", edgecolor="black", linewidth=0.5)
    ax2.set_xticks(x)
    ax2.set_xticklabels(labels, rotation=20, ha="right")
    ax2.set_ylabel("Pooled pass rate (all 42 modules)")
    ax2.set_ylim(0, max(0.5, max(pass_rates) * 1.3))
    ax2.set_title("(b) Pass rate per condition (regression check)")
    ax2.grid(axis="y", linestyle=":", alpha=0.4)
    for i, v in enumerate(pass_rates):
        ax2.text(i, v + 0.01, f"{v:.3f}", ha="center", fontsize=9)

    fig.suptitle("Set 1 (STITCH conditions, RTLLM): tool cost drops, pass rate holds")
    fig.tight_layout()
    fig.savefig(OUT_FIG_PNG, dpi=300)
    fig.savefig(OUT_FIG_PDF)


def main():
    entries = _data.load_master_log()
    per_cond, dropped_unexpected, n_read = collect_costs(entries)
    pass_rates = pooled_pass_rate(entries)
    rows = build_summary(per_cond, pass_rates)

    # Structural check (per the brief's Verification section): baseline
    # NEVER invokes Verilator/Yosys -- if this isn't exactly 0.00,
    # something is wrong with the extraction, not with the data.
    baseline_row = next(r for r in rows if r["condition"] == "baseline")
    assert baseline_row["mean_tool_calls"] == 0.0, (
        f"baseline mean tool calls/run must be exactly 0.00, got "
        f"{baseline_row['mean_tool_calls']} -- extraction bug, investigate "
        "before trusting anything else in this file."
    )

    by_cond = {r["condition"]: r for r in rows}
    sem_adv_calls = by_cond["sem_adv"]["mean_tool_calls"]
    sem_esc_calls = by_cond["sem_escalate"]["mean_tool_calls"]
    reduction_pct = (sem_adv_calls - sem_esc_calls) / sem_adv_calls * 100

    write_tex(rows, reduction_pct)
    write_csv(rows)
    write_fig(rows)

    print(f"Read cost data for {n_read} runs "
          f"({len(dropped_unexpected)} unexpectedly missing/malformed beyond "
          f"the 6 known transient errors).")
    if dropped_unexpected:
        print("  Unexpectedly dropped cells:", dropped_unexpected, file=sys.stderr)
    print()
    print(f"{'condition':<24}{'tokens/run':>12}{'tool calls/run':>16}{'iters/run':>12}{'pass rate':>12}")
    for r in rows:
        print(f"{r['condition']:<24}{r['mean_tokens']:>12.0f}{r['mean_tool_calls']:>16.2f}"
              f"{r['mean_iterations']:>12.2f}{r['pass_rate']:>12.3f}  ({r['n_pass']}/{r['n_valid']})")
    print()
    print(f"Tool-invocation reduction (sem_adv -> sem_escalate): {reduction_pct:.1f}%")
    print("Phase 1's matched result (PHASE1_FINDINGS.md Sec.1): ~35-45%")
    print(f"Wrote {OUT_TEX}, {OUT_CSV}, {OUT_FIG_PNG}, {OUT_FIG_PDF}")


if __name__ == "__main__":
    main()
