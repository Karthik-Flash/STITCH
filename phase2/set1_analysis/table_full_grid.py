"""
phase2/set1_analysis/table_full_grid.py -- deliverable 3: full 42 module
x (3 models x 4 conditions = 12) grid, each cell a pass count. Row
structure identical to Twin's table1_full_grid.tex -- grouped by
(functional_class, difficulty_tier), same class/tier definitions
(Twin's module_categories.json, reused verbatim, not recomputed).

Columns: 3 model blocks (gemma3:4b, llama3.1, deepseek-coder) in that
order, each with 4 sub-columns (baseline, sem_adv, sem_escalate,
sem_escalate_restart) -- per the brief.

Cell format: "p/n" where n is normally 3; for the 3 cells touched by a
known transient-timeout error, n is < 3 (or 0) -- rendered distinctly
("0/0" is NOT the same claim as "0/3": one is "no data", the other is
"every replicate failed"; a 0/0 cell is marked "err" in LaTeX, grey-
filled, never colored red like a real 0/3). Color-coded green (light) if
p==n (all replicates passed, n>0) or red (light) if p==0 and n>0 (a real,
data-backed zero) -- matching Twin's convention exactly for cells that
have real data.

Usage: python phase2/set1_analysis/table_full_grid.py
Output: table_full_grid.tex, table_full_grid.csv
"""
import csv
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
import _data  # noqa: E402

OUT_TEX = os.path.join(_HERE, "table_full_grid.tex")
OUT_CSV = os.path.join(_HERE, "table_full_grid.csv")

COND_ABBREV = {
    "baseline": "base", "sem_adv": "s\\_adv",
    "sem_escalate": "s\\_esc", "sem_escalate_restart": "s\\_esc\\_r",
}
COND_ABBREV_PLAIN = {
    "baseline": "base", "sem_adv": "s_adv",
    "sem_escalate": "s_esc", "sem_escalate_restart": "s_esc_r",
}


def _tex_escape(s):
    return s.replace("_", r"\_")


def _cell(p, n):
    if n == 0:
        return f"{p}/{n}", "err"
    if p == n:
        return f"{p}/{n}", "green"
    if p == 0:
        return f"{p}/{n}", "red"
    return f"{p}/{n}", None


def build():
    entries = _data.load_master_log()
    counts = _data.pivot_pass_counts(entries)
    categories = _data.load_categories()
    modules = _data.sorted_modules_by_group(categories)

    rows = []
    last_group = None
    for m in modules:
        info = categories[m]
        group = (info["functional_class"], info["difficulty_tier"])
        group_label = None
        if group != last_group:
            group_label = f"{info['functional_class']} -- {info['difficulty_tier']}"
            last_group = group
        cells = []  # [(text, color)] in column order: model x condition
        for model in _data.MODELS:
            for cond in _data.CONDITIONS:
                p, n = counts[(m, model, cond)]
                cells.append(_cell(p, n))
        rows.append((m, group_label, cells))
    return rows


def write_tex(rows):
    n_cols = len(_data.MODELS) * len(_data.CONDITIONS)
    lines = []
    lines.append("% Auto-generated by phase2/set1_analysis/table_full_grid.py -- do not hand-edit.")
    lines.append("% Requires \\usepackage{colortbl} or \\usepackage[table]{xcolor} in the preamble.")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\tiny")
    lines.append(r"\caption{Set 1: pass count (of $N{=}3$) per module, model, and STITCH condition, "
                 r"42 modules, 1512 runs (6 transient timeouts dropped, marked ``err''), $T{=}0.1$.}")
    lines.append(r"\label{tab:set1-full-grid}")
    lines.append(r"\begin{tabular}{l" + "c" * n_cols + "}")
    lines.append(r"\toprule")

    # top header: model names spanning 4 columns each
    model_header = ["\\multicolumn{4}{c}{" + _tex_escape(_data.MODEL_DISPLAY[m]) + "}" for m in _data.MODELS]
    lines.append("& " + " & ".join(model_header) + r" \\")
    cmidrules = " ".join(f"\\cmidrule(lr){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(len(_data.MODELS)))
    lines.append(cmidrules)

    cond_header = [COND_ABBREV[c] for _ in _data.MODELS for c in _data.CONDITIONS]
    lines.append("Module & " + " & ".join(cond_header) + r" \\")
    lines.append(r"\midrule")

    for module, group_label, cells in rows:
        if group_label:
            lines.append(r"\multicolumn{" + str(n_cols + 1) + "}{l}{\\textbf{"
                          + _tex_escape(group_label) + "}} \\\\")
        rendered = []
        for text, color in cells:
            if color == "green":
                rendered.append(f"\\cellcolor{{green!15}}{text}")
            elif color == "red":
                rendered.append(f"\\cellcolor{{red!15}}{text}")
            elif color == "err":
                rendered.append(f"\\cellcolor{{gray!20}}{text}")
            else:
                rendered.append(text)
        lines.append(_tex_escape(module) + " & " + " & ".join(rendered) + r" \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    with open(OUT_TEX, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_csv(rows):
    header = ["module", "functional_class_tier_group"]
    for model in _data.MODELS:
        for cond in _data.CONDITIONS:
            header.append(f"{_data.MODEL_DISPLAY[model]}_{COND_ABBREV_PLAIN[cond]}")
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        last_group = None
        for module, group_label, cells in rows:
            group_for_csv = group_label if group_label else last_group
            if group_label:
                last_group = group_label
            w.writerow([module, group_for_csv] + [text for text, _color in cells])


def main():
    rows = build()
    assert len(rows) == 42, f"expected 42 rows, got {len(rows)}"
    for _m, _g, cells in rows:
        assert len(cells) == len(_data.MODELS) * len(_data.CONDITIONS)

    write_tex(rows)
    write_csv(rows)

    total_pass = sum(int(text.split("/")[0]) for _m, _g, cells in rows for text, _c in cells)
    total_valid = sum(int(text.split("/")[1]) for _m, _g, cells in rows for text, _c in cells)
    entries = _data.load_master_log()
    direct_pass = sum(1 for e in _data.valid_entries(entries))
    direct_pass_count = sum(1 for e in _data.valid_entries(entries) if e["pass"])

    print(f"Wrote {OUT_TEX} and {OUT_CSV} ({len(rows)} rows x {len(_data.MODELS)*len(_data.CONDITIONS)} cols)")
    print(f"Sum of all cell pass-counts: {total_pass} (cross-check: {direct_pass_count})")
    print(f"Sum of all cell valid-counts: {total_valid} (cross-check: {direct_pass} valid entries)")
    assert total_pass == direct_pass_count
    assert total_valid == direct_pass


if __name__ == "__main__":
    main()
