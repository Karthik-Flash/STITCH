"""
phase2/set3_analysis/per_model_tier.py -- deliverable 1: per-model
recoverable-band pass rate, one row per (model, condition), for Set 3's
3 larger models. The granular view behind the pooled 4-row headline
table -- the pooled numbers can look flat/uniform while individual
models move in different directions (they do here; see
SET3_ANALYSIS.md's per-model section).

Usage: python phase2/set3_analysis/per_model_tier.py
Output: per_model_tier.csv, per_model_tier.tex
"""
import csv
import os
import sys

from statsmodels.stats.proportion import proportion_confint

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
import _data  # noqa: E402

OUT_CSV = os.path.join(_HERE, "per_model_tier.csv")
OUT_TEX = os.path.join(_HERE, "per_model_tier.tex")


def build():
    entries = _data.load_master_log()
    counts = _data.pivot_pass_counts(entries)
    mods = _data.module_list(entries)

    rows = []
    for model in _data.MODELS:
        for cond in _data.CONDITIONS:
            n_pass = sum(counts[(m, model, cond)][0] for m in mods)
            n_valid = sum(counts[(m, model, cond)][1] for m in mods)
            rate = n_pass / n_valid if n_valid else float("nan")
            lo, hi = proportion_confint(n_pass, n_valid, alpha=0.05, method="wilson") if n_valid else (float("nan"), float("nan"))
            rows.append({
                "model": model, "condition": cond, "n_pass": n_pass, "n_valid": n_valid,
                "rate": rate, "ci_lo": lo, "ci_hi": hi,
            })
    return rows


def write_csv(rows):
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["model", "condition", "n_pass", "n_valid", "pass_rate", "wilson_ci_lo", "wilson_ci_hi"])
        for r in rows:
            w.writerow([r["model"], r["condition"], r["n_pass"], r["n_valid"],
                         f"{r['rate']:.4f}", f"{r['ci_lo']:.4f}", f"{r['ci_hi']:.4f}"])


def _tex_escape(s):
    return s.replace("_", r"\_")


def write_tex(rows):
    lines = []
    lines.append("% Auto-generated by phase2/set3_analysis/per_model_tier.py -- do not hand-edit.")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Set 3: recoverable-band pass rate per model and STITCH condition "
                 r"(17 modules, $N{=}3$, $T{=}0.1$; 2 transient timeouts dropped -- "
                 r"qwen2.5-coder:32b/sem\_escalate\_restart only). Wilson 95\% CI.}")
    lines.append(r"\label{tab:set3-per-model-tier}")
    lines.append(r"\begin{tabular}{llrrr}")
    lines.append(r"\toprule")
    lines.append(r"Model & Condition & Passes/n & Rate & 95\% CI \\")
    lines.append(r"\midrule")
    last_model = None
    for r in rows:
        model_cell = _tex_escape(r["model"]) if r["model"] != last_model else ""
        last_model = r["model"]
        lines.append(
            f"{model_cell} & {_tex_escape(r['condition'])} & {r['n_pass']}/{r['n_valid']} & "
            f"{r['rate']*100:.1f}\\% & [{r['ci_lo']*100:.1f}, {r['ci_hi']*100:.1f}] \\\\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    with open(OUT_TEX, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def main():
    rows = build()
    assert len(rows) == len(_data.MODELS) * len(_data.CONDITIONS) == 12

    write_csv(rows)
    write_tex(rows)

    print(f"Wrote {OUT_CSV} and {OUT_TEX} ({len(rows)} rows)")
    print()
    for r in rows:
        print(f"{r['model']:<22}{r['condition']:<24}{r['n_pass']:>3}/{r['n_valid']:<4}"
              f"{r['rate']*100:>7.1f}%  95% CI [{r['ci_lo']*100:.1f}, {r['ci_hi']*100:.1f}]")

    # cross-check: pooled sum across the 3 models must equal the brief's
    # stated pooled numbers.
    pooled = {c: [0, 0] for c in _data.CONDITIONS}
    for r in rows:
        pooled[r["condition"]][0] += r["n_pass"]
        pooled[r["condition"]][1] += r["n_valid"]
    expected = {"baseline": (86, 153), "sem_adv": (85, 153), "sem_escalate": (90, 153),
                "sem_escalate_restart": (88, 151)}
    for c, (p, n) in expected.items():
        got = tuple(pooled[c])
        assert got == (p, n), f"{c}: pooled {got} != expected {(p, n)}"
    print("\nPooled cross-check against the brief's stated numbers: OK")


if __name__ == "__main__":
    main()
