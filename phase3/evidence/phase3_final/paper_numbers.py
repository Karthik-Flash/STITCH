#!/usr/bin/env python3
"""Every Phase 3 number quoted in paper/STITCH_EXT_v7.tex Section 9, as run (tb.v, the first write-up) and under the
pre-registered sign-off oracle, plus the final-batch numbers (baseline_gate, qwen2.5-coder:32b). Reads the same run
directories and signoff_cache.json as analyze_phase3.py --final (fill the cache first with --score-signoff).
Repo root:  python phase3/evidence/phase3_final/paper_numbers.py > phase3/evidence/phase3_final/PAPER_NUMBERS.md"""
import json
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
P3 = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(P3, "runner"))
from analyze_phase3 import MODELS, M32, apply_signoff, fp, load_many, pcontrast, rate, sg  # noqa: E402

sys.stdout.reconfigure(encoding="utf-8", newline="\n")
dirs = [os.path.join(P3, "results", d) for d in ("phase3_run", "phase3_gate_ctrl", "phase3_32b")]
runs, meta, idx = load_many(dirs, os.path.join(P3, "tasks"))
apply_signoff(runs, os.path.join(P3, "tasks"), allow_sim=False)
R6 = [r for r in runs if r["model"] in MODELS]
C = ["baseline", "raw_adv", "sem_adv_v2", "sem_adv_v3", "sem_esc_restart_v3", "baseline_gate"]
m6 = lambda r: r["model"] in MODELS


def sel(cond=None, model=None, stratum=None, rs=R6):
    return [r for r in rs if (cond is None or r["condition"] == cond) and (model is None or r["model"] == model)
            and (stratum is None or r["silent"] == (stratum == "silent"))]


def k(rs, key):
    return sum(bool(r[key]) for r in rs)


def con(A, B, key, keep, label):
    c = pcontrast(idx, A, B, lambda r: r[key], keep, label)
    return f"{c['A'].split(' (')[0]} vs {c['B'].split(' (')[0]}, {sg(c['delta'])} pts [{sg(c['lo'])}, {sg(c['hi'])}], " \
           f"sign-flip p {fp(c['p'])}, discordant {c['disc']}"


print("# Phase 3 numbers for the paper: as run (tb.v) vs sign-off oracle\n")
print("Generated by `phase3/evidence/phase3_final/paper_numbers.py`. Six original models unless stated. "
      "`as run` = clean_pass under tb.v (the numbers now in STITCH_EXT_v7.tex Section 9); `sign-off` = signoff_clean "
      "(pre-registered primary metric). Contrast CIs: (model, task) cell bootstrap; labels differ from PHASE3_FINAL.md, "
      "so the last digit of a CI can differ from that file, which is the reference.\n")
print("## Table 9 (per condition)\n")
print("| condition | func_pass (tb.v) | clean as run | signoff_clean | silent structural pass (old) | signed_off_defective | tokens/run | calls/run | tool rounds/run |")
print("|---|---|---|---|---|---|---|---|---|")
for c in C:
    rs = sel(c); n = len(rs)
    print(f"| {c} | {rate(k(rs, 'func_pass'), n)['fmt']} | {rate(k(rs, 'clean_pass'), n)['fmt']} | "
          f"{rate(k(rs, 'signoff_clean'), n)['fmt']} | {rate(k(rs, 'silent_structural_pass'), n)['fmt']} | "
          f"{rate(k(rs, 'signed_off_defective'), n)['fmt']} | {sum(r['tokens'] for r in rs) / n:,.0f} | "
          f"{sum(r['llm_calls'] for r in rs) / n:.2f} | {sum(r['tool_feedback_iters'] for r in rs) / n:.2f} |")

print("\n## Claims in Section 9, one per line\n")
b = sel("baseline", stratum="silent")
print(f"- (1) baseline on the six sim-silent tasks: signed off {k(b, 'signed_off_defective')}/{len(b)}, with 0 LLM calls in "
      f"{sum(r['llm_calls'] == 0 for r in b)}/{len(b)}.")
for key, lab in (("clean_pass", "as run"), ("signoff_clean", "sign-off")):
    print(f"- (2) v3 vs raw, {lab}: {con('sem_adv_v3', 'raw_adv', key, m6, 'pn:v3raw:' + key)}")
    print(f"- (2) v2 vs raw, {lab}: {con('sem_adv_v2', 'raw_adv', key, m6, 'pn:v2raw:' + key)}")
v3, raw, esc, base = (sel(c) for c in ("sem_adv_v3", "raw_adv", "sem_esc_restart_v3", "baseline"))
mean = lambda rs, f: sum(f(r) for r in rs) / len(rs)
print(f"- (2) v3 vs raw cost: calls {100 * (mean(v3, lambda r: r['llm_calls']) / mean(raw, lambda r: r['llm_calls']) - 1):+.1f}%, "
      f"tokens {100 * (mean(v3, lambda r: r['tokens']) / mean(raw, lambda r: r['tokens']) - 1):+.1f}% (outcome-independent)")
for key, lab in (("clean_pass", "as run"), ("signoff_clean", "sign-off")):
    tpc = {c: sum(r["tokens"] for r in sel(c)) / k(sel(c), key) for c in ("sem_adv_v3", "raw_adv")}
    print(f"- (2) tokens per clean pass, {lab}: v3 {tpc['sem_adv_v3']:,.0f}, raw {tpc['raw_adv']:,.0f}")
for key, fk, lab in (("clean_pass", "first_clean", "as run"), ("signoff_clean", "first_so_clean", "sign-off")):
    for r in runs:
        r.setdefault("first_clean", next((p["iter"] for p in r["per_iter"] if p["clean_pass"]), None))
    fc = {c: rate(sum(r[fk] is not None and r[fk] <= 1 for r in sel(c)), 198)["fmt"] for c in ("sem_adv_v3", "raw_adv", "baseline", "baseline_gate", "sem_esc_restart_v3")}
    print(f"- (2) clean after the first call, {lab}: " + "; ".join(f"{c} {v}" for c, v in fc.items()))
for mo in ("llama3.2:3b", "qwen2.5-coder:7b", "qwen2.5-coder:14b"):
    for key, lab in (("clean_pass", "as run"), ("signoff_clean", "sign-off")):
        a, bb = sel("sem_adv_v3", mo), sel("raw_adv", mo)
        print(f"- (2) {mo}, {lab}: v3 {k(a, key)}/33, raw {k(bb, key)}/33, {sg(100 * (k(a, key) - k(bb, key)) / 33)} pts")
lt = {c: [r for r in sel(c) if r["latch_count_before"]] for c in C}
print("- (1) latch-bearing tasks, runs ending latch-free with Yosys OK (structural, oracle-independent): " + "; ".join(
    f"{c} {sum(r['latch_count_after'] == 0 and bool(r['final_yosys_ok']) for r in v)}/{len(v)} "
    f"({100 * sum(r['latch_count_after'] == 0 and bool(r['final_yosys_ok']) for r in v) / len(v):.0f}%)" for c, v in lt.items()))
print(f"- (3) escalation tool rounds vs v3: {100 * (mean(esc, lambda r: r['tool_feedback_iters']) / mean(v3, lambda r: r['tool_feedback_iters']) - 1):+.1f}%")
vis = lambda r: m6(r) and not r["silent"]
for key, lab in (("clean_pass", "as run"), ("signoff_clean", "sign-off")):
    print(f"- (3) esc vs baseline, sim-visible, {lab}: {con('sem_esc_restart_v3', 'baseline', key, vis, 'pn:escbase:' + key)}")
    s = {c: k(sel(c, 'llama3.2:3b', 'visible'), key) for c in ("baseline", "raw_adv", "sem_esc_restart_v3", "baseline_gate")}
    print(f"- (3) llama3.2:3b sim-visible, {lab}: " + ", ".join(f"{c} {v}/15" for c, v in s.items()))
focus = {"register_1bit", "ni_flit_pack", "register_4bit", "register_32bit"}
for key, lab in (("clean_pass", "as run"), ("signoff_clean", "sign-off")):
    a = [r for r in sel("sem_adv_v2") if r["task"] in focus]; bb = [r for r in sel("sem_adv_v3") if r["task"] in focus]
    print(f"- (5) four focus tasks, {lab}: v2 {k(a, key)}/72, v3 {k(bb, key)}/72 (no focus task has a differing tb_signoff.v)")

print("\n## Final batch: control arm\n")
for key, lab in (("signoff_clean", "sign-off (PRIMARY)"), ("clean_pass", "as run")):
    for A, B, st in (("sem_esc_restart_v3", "baseline_gate", None), ("sem_adv_v3", "baseline_gate", None),
                     ("baseline_gate", "raw_adv", None), ("baseline_gate", "baseline", "visible")):
        keep = (lambda r: m6(r) and not r["silent"]) if st else m6
        print(f"- {A} − {B}{', sim-visible' if st else ''}, {lab}: {con(A, B, key, keep, 'pn:gate:' + A + B + key)}")
g = sel("baseline_gate"); fail = [r for r in g if not r["signoff_clean"]]
print(f"- baseline_gate runs not signoff_clean: {len(fail)}/198; of these, v3 would have fired on the RTL the verdict was "
      f"given on in {sum(bool(r['would_fire']) for r in fail)}, and on the returned RTL in {sum(bool(r['would_fire_final']) for r in fail)}")
gs = sel("baseline_gate", stratum="silent"); es = sel("sem_esc_restart_v3", stratum="silent")
print(f"- sim-silent tasks, simulation still passing at the end (loop_pass): baseline_gate {k(gs, 'func_pass')}/108, "
      f"sem_esc_restart_v3 {k(es, 'func_pass')}/108")

print("\n## Final batch: qwen2.5-coder:32b (N=3, 33 runs per condition)\n")
R32 = [r for r in runs if r["model"] == M32]
for c in C:
    rs = sel(c, rs=R32); sil = [r for r in rs if r["silent"]]; vi = [r for r in rs if not r["silent"]]
    print(f"- {c}: signoff_clean {k(rs, 'signoff_clean')}/33 (sim-silent {k(sil, 'signoff_clean')}/18, sim-visible "
          f"{k(vi, 'signoff_clean')}/15); as run {k(rs, 'clean_pass')}/33; tokens/run {sum(r['tokens'] for r in rs) / 33:,.0f}; "
          f"calls/run {sum(r['llm_calls'] for r in rs) / 33:.2f}; signed off defective {k(rs, 'signed_off_defective')}/33 "
          f"(sim-silent {k(sil, 'signed_off_defective')}/18)")
ns = defaultdict(int)
for r in R32:
    if not r["signoff_clean"] and r["condition"] != "baseline":
        ns[(r["task"], r["condition"])] += 1
print(f"- 32B non-baseline runs that are not signoff_clean, by (task, condition): {dict(sorted(ns.items()))}")

# ---------------------------------------------------------------------------- API ladder rows (descriptive)
print("\n## Ladder rows: API models (Part A, phase2/results/p3_api/full; descriptive, N=3, never pooled)\n")
api_dirs = [os.path.join(os.path.dirname(P3), "phase2", "results", "p3_api", "full", p) for p in ("openai", "anthropic")]
api, _, _ = load_many(api_dirs, os.path.join(P3, "tasks"))
apply_signoff(api, os.path.join(P3, "tasks"), allow_sim=False)
prov = {k: sorted({str(r[k]) for r in api}) for k in ("protocol", "interp_v3_version", "base_interp_sha256_lf", "temperature",
                                                       "max_iters", "sem_include_raw")}
prov["runner"] = sorted({r["provenance"]["runner_sha256_lf"] for r in api})
prov["toolchain"] = sorted({json.dumps(r["provenance"]["toolchain"], sort_keys=True) for r in api})
print(f"- provenance over {len(api)} runs: {json.dumps(prov)}")
for mo in sorted({r["model"] for r in api}):
    for c in C:
        rs = sel(c, mo, rs=api); sil = [r for r in rs if r["silent"]]; vi = [r for r in rs if not r["silent"]]
        print(f"- {mo} {c}: signoff_clean {k(rs, 'signoff_clean')}/{len(rs)} (sim-silent {k(sil, 'signoff_clean')}/{len(sil)}, "
              f"sim-visible {k(vi, 'signoff_clean')}/{len(vi)}); as run {k(rs, 'clean_pass')}/{len(rs)}; signed off defective "
              f"{k(rs, 'signed_off_defective')}/{len(rs)} (sim-silent {k(sil, 'signed_off_defective')}/{len(sil)}); tokens/run {sum(r['tokens'] for r in rs) / len(rs):,.0f}")
na = defaultdict(int)
for r in api:
    if not r["signoff_clean"] and r["condition"] != "baseline":
        na[(r["model"], r["task"], r["condition"])] += 1
print(f"- API non-baseline runs that are not signoff_clean, by (model, task, condition): {dict(sorted(na.items()))}")

# ---------------------------------------------------------------------------- extra rows for PHASE3_MPSOC.tex
print("\n## Extra rows for PHASE3_MPSOC.tex (six models unless stated)\n")
for mo in MODELS:
    print(f"- per model {mo}: signoff_clean of 33: " + ", ".join(f"{c} {k(sel(c, mo), 'signoff_clean')}" for c in C)
          + "; sim-visible of 15: " + ", ".join(f"{c} {k(sel(c, mo, 'visible'), 'signoff_clean')}" for c in ("baseline", "sem_esc_restart_v3", "baseline_gate")))
E = sel("sem_esc_restart_v3")
for flag in (False, True):
    rs = [r for r in E if (r["escalated_at"] is not None) == flag]
    print(f"- sem_esc_restart_v3 {'escalated' if flag else 'never escalated'}: {len(rs)} runs, signoff_clean {k(rs, 'signoff_clean')}, "
          f"clean_pass as run {k(rs, 'clean_pass')}")
bounds = [json.loads(l) for l in open(os.path.join(P3, "evidence", "compose_bounds.jsonl")) if l.strip()]
bnd = {b["design"]: b["latch_cells_excl_crashed"] for b in bounds if b["repaired_modules"]}
comp = [json.loads(l) for d in dirs for l in open(os.path.join(d, "compose_results.jsonl")) if l.strip()]
print(f"- golden latch bounds per design (compose_bounds.jsonl): {bnd}")
for grp, keep in (("six models", lambda x: x["model"] in MODELS), (M32, lambda x: x["model"] == M32)):
    for d in ("mesh2x2", "mesh3x3", "mpsoc"):
        row = []
        for c in C:
            X = [x for x in comp if keep(x) and x["design"] == d and x["condition"] == c]
            ok = sum(bool(x["top_level_synthesis_pass"]) for x in X)
            atb = sum(bool(x["top_level_synthesis_pass"] and x["top_latch_cells"] is not None and x["top_latch_cells"] <= bnd[d]) for x in X)
            row.append(f"{c} {ok}/{len(X)} (at bound {atb})")
        print(f"- composition {grp} {d}: " + "; ".join(row))
gs = sel("baseline_gate")
print("- baseline_gate per task: " + "; ".join(
    f"{t} signoff {k([r for r in gs if r['task'] == t], 'signoff_clean')}/18" for t in sorted(meta)))
